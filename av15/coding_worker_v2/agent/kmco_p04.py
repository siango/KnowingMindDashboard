"""KMCO P04 five-stage planning verification over existing KM_TASK_PLAN_V1.

No model inference, command execution, task creation or authority promotion.
P04 reuses canonical agent.planner validation and topological sort.
"""
import hashlib
import json

from .planner import PlanError, validate_plan_dict, order_tasks


class P04Blocked(ValueError):
    pass


def goal_parser(raw, mission_id):
    """P04-M01: accept only typed original plan of exact existing mission."""
    if (not isinstance(raw, dict) or not isinstance(mission_id,str)
            or raw.get("mission_id") != mission_id):
        raise P04Blocked("P04_MISSION_OR_GOAL_MISMATCH")
    try:
        return validate_plan_dict(raw)
    except PlanError as exc:
        raise P04Blocked(exc.reason) from None


def scope_binder(plan, owner_node):
    """P04-M02: pin exact owner and nonempty approved scope for each task."""
    if not isinstance(owner_node,str) or plan.owner_node != owner_node:
        raise P04Blocked("P04_OWNER_NOT_BOUND")
    if any(not task.allowed_paths for task in plan.tasks):
        raise P04Blocked("P04_TASK_SCOPE_REQUIRED")
    return {task.task_id: list(task.allowed_paths) for task in plan.tasks}


def task_atomizer(plan):
    """P04-M03: deterministic unique task set, no autogenerated IDs."""
    if not plan.tasks or len({t.task_id for t in plan.tasks}) != len(plan.tasks):
        raise P04Blocked("P04_TASK_COLLISION")
    return [task.task_id for task in plan.tasks]


def dependency_dag(plan):
    """P04-M04: existing planner's cycle and missing-dependency gate."""
    try:
        return [task.task_id for task in order_tasks(plan)]
    except PlanError as exc:
        raise P04Blocked(exc.reason) from None


def plan_validator(raw, mission_id, owner_node):
    """P04-M05: output a source-pinned plan *preview*, never admit tasks."""
    plan=goal_parser(raw, mission_id)
    scope=scope_binder(plan, owner_node)
    ids=task_atomizer(plan)
    order=dependency_dag(plan)
    digest=hashlib.sha256(json.dumps(raw,sort_keys=True,
                    ensure_ascii=False,separators=(",",":"),allow_nan=False).encode()).hexdigest()
    return {"circuit":"P04","steps_completed":[f"P04-M{i:02d}" for i in range(1,6)],
            "status":"VALIDATED_PLAN_PREVIEW_ONLY","plan_sha256":digest,
            "mission_id":mission_id,"owner_node":owner_node,
            "task_count":len(ids),"task_ids":ids,"ordered_task_ids":order,
            "scoped_tasks":len(scope),"admitted":False,"dispatched":False,
            "authority_granted":False,"independent_qc":"NOT_RUN",
            "evidence_source":"CALLER_SUPPLIED_PLAN_VERIFIED_BY_EXISTING_PLANNER"}
